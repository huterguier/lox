AxisName = Hashable


def spool(
    fun: Callable,
    argnames: Iterable[str] | None = None,
    tags: Iterable[str] | None = None,
    keep_logs: bool = False,
    interval: int | None = None,
    reduce: str | None = None,
    prefix: str = "",
) -> Callable:
    """
    Spools a function to extract logs generated during its execution.
    Logs are generated by every call to ``lox.log`` within the function.
    Note that spooling also has to obey the underlying laws of JAX.
    Hence all shapes and lengths of the logs must be inferrable during compile time.
    As a direct consequence, loops with non-static lengths (e.g. while loops) are not supported.
    Another implication of this is that spooling an already jitted function that contains
    logging operations will trigger recompilation.

    Args:
        fun (Callable): The function to be spooled.
        argnames (Iterable[str] | None): An optional list of argument names to be spooled.
        tags (Iterable[str] | None): An optional list of tags to filter the logs.
        keep_logs (bool): Whether to keep logs in the jaxpr.
        interval (int | None): An optional interval to subsample the logs.
        reduce (str | None): An optional reduction method to apply to the logs.
        prefix (str): An optional prefix to add to the log keys.

    Returns:
        Callable: A wrapped function that returns the spooled jaxpr and logs.

    Example:
        Here is an example of how to use ``spool`` to extract logs from a function.

        >>> def f(x):
        >>>     lox.log({"x": x})
        >>>     return x + 1.0
        >>> spool(f)(1.0)
        (2.0, {'x': 1.0})

        Spooling works with arbitrarily nested functions and higher order primitives such as
        ``jax.lax.scan`` or ``jax.lax.cond``.
        The following example shows how to use spooling with a scan operation over the
        previously defined function ``f``.

        >>> def g(xs):
        >>>     carry, ys = jax.lax.scan(lambda c, x: (f(c), x), xs)
        >>>     lox.log({"carry": carry})
        >>> return ys
        >>> spool(g)(jnp.arange(3))
        (Array([2., 3., 4.]), {'carry': 3., 'x': Array([0., 1., 2.])})

        When logging inside of ``jax.lax.cond`` all branches must have the same log structure.
        In this case, both branches return a logdict containing only the key :string:`x`.

        >>> def h(x):
        >>>     return jax.lax.cond(x > 0, lambda x: f(x), lambda x: f(x + 1), x)
        >>> x = 3.0
        >>> spool(h)(x)
        (4.0, {'x': 3.0})

        The optional argument `keep_logs` can be set to `True` to keep the logs in the jaxpr.
        By default, spooling a function twice

        >>> def j(x):
        >>>     y, logs = spool(f)(x)
        >>>     return y
        >>> spool(j)(1.0)
        2.0

    """

    @wraps(fun)
    def wrapped(*args, **kwargs):
        args_flat, structure = jax.tree.flatten((args, kwargs))
        static_argnums = tuple(i for i, arg in enumerate(args_flat) if is_hashable(arg))
        closed_jaxpr, out_spooled_shape = make_spooled_jaxpr(
            flatten(fun, structure),
            static_argnums=static_argnums,
            argnames=argnames,
            tags=tags,
            keep_logs=keep_logs,
        )(*args_flat)
        dynamic_args_flat = tuple(arg for arg in args_flat if not is_hashable(arg))
        out_spooled_structure = jax.tree.structure(out_spooled_shape)
        out_spooled_flat = jax.core.eval_jaxpr(
            closed_jaxpr.jaxpr, closed_jaxpr.literals, *dynamic_args_flat
        )
        out, logs = jax.tree_util.tree_unflatten(
            out_spooled_structure, out_spooled_flat
        )
        if interval is not None:
            logs = logs.slice[::interval]
        if reduce is not None:
            logs = logs.reduce(reduce)
        if prefix:
            logs = logs.prefix(prefix)
        return out, logs

    return wrapped


def make_spooled_jaxpr(
    fun: Callable,
    static_argnums: int | Iterable[int] = (),
    argnames: Iterable[str] | None = None,
    tags: Iterable[str] | None = None,
    keep_logs: bool = False,
) -> Callable[..., tuple[ClosedJaxpr, Any]]:
    """
    Creates a spooled jaxpr for the given function, extracting logs and their shapes.

    Args:
        fun (Callable): The function to create a jaxpr for.
        static_argnums (int | Iterable[int]): The indices of static arguments.
        argnames (Optional[Iterable[str]]): An optional list of argument names to be spooled.
        tags (Optional[Iterable[str]]): An optional list of tags to filter the logs.
        keep_logs (bool): Whether to keep logs in the jaxpr.
    Returns:
        Callable[..., ClosedJaxpr | tuple[ClosedJaxpr, Any]]: A wrapped function that returns the jaxpr and logs.
    """

    def make_jaxpr_f(*args, **kwargs):
        closed_jaxpr, out_shape = jax.make_jaxpr(
            fun,
            static_argnums=static_argnums,
            return_shape=True,
        )(*args, **kwargs)
        new_jaxpr, logs = spool_jaxpr(closed_jaxpr.jaxpr, argnames=argnames, tags=tags)
        closed_jaxpr = ClosedJaxpr(new_jaxpr, closed_jaxpr.consts)
        logs_shape = jax.tree_util.tree_map(
            lambda v: ShapeDtypeStruct(v.aval.shape, v.aval.dtype), logs
        )
        if not keep_logs:
            stripped = strip_jaxpr(closed_jaxpr.jaxpr, argnames=argnames, tags=tags)
            closed_jaxpr = ClosedJaxpr(stripped, closed_jaxpr.consts)
        return closed_jaxpr, (out_shape, logs_shape)

    make_jaxpr_f.__module__ = "jax"
    if hasattr(fun, "__qualname__"):
        make_jaxpr_f.__qualname__ = f"make_jaxpr({fun.__qualname__})"
    if hasattr(fun, "__name__"):
        make_jaxpr_f.__name__ = f"make_jaxpr({fun.__name__})"
    return make_jaxpr_f


def apply(f: Callable, ctx, *invars: Any) -> tuple[JaxprEqn, Any]:
    """
    Creates a call_p equation that applies f to invars.

    Args:
        f (Callable): The function to apply.
        ctx: The JaxprEqnContext for the new equation.
        *invars: The input variables to the function.
    Returns:
        tuple[JaxprEqn, Any]: The new equation and the output variables.
    """
    invars_avals = jax.tree.map(lambda invar: invar.aval, invars)
    closed_jaxpr_f, shape_f = jax.make_jaxpr(f, return_shape=True)(*invars_avals)
    structure_f = jax.tree.structure(shape_f)
    jaxpr_f = closed_jaxpr_f.jaxpr
    if closed_jaxpr_f.consts:
        const_literals = [Literal(c, jax.typeof(c)) for c in closed_jaxpr_f.consts]
        call_jaxpr = jaxpr_f.replace(
            constvars=[],
            invars=[*jaxpr_f.constvars, *jaxpr_f.invars],
        )
        eqn_invars = [*const_literals, *jax.tree.leaves(invars)]
    else:
        call_jaxpr = jaxpr_f
        eqn_invars = jax.tree.leaves(invars)
    eqn_f = JaxprEqn(
        eqn_invars,
        call_jaxpr.outvars,
        jax.extend.core.primitives.call_p,
        {"call_jaxpr": call_jaxpr},
        (),
        source_info_util.current(),
        ctx,
    )
    outvars = jax.tree.unflatten(structure_f, call_jaxpr.outvars)
    return eqn_f, outvars


def spool_jaxpr(
    jaxpr: Jaxpr, argnames: Iterable[str] | None, tags: Iterable[str] | None
) -> tuple[Jaxpr, logdict]:
    """
    Spools the logs from a jaxpr, extracting logs and their shapes from each equation.
    Returns a new Jaxpr with log outputs appended (does not mutate the input).

    Args:
        jaxpr (Jaxpr): The jaxpr to spool.
        argnames (Iterable[str] | None): An optional list of argument names to be spooled.
        tags (Iterable[str] | None): An optional list of tags to filter the logs.
    Returns:
        tuple[Jaxpr, logdict]: The new jaxpr with log outputs and the logs.
    """
    ctx = jaxpr.eqns[0].ctx if jaxpr.eqns else None

    def spool_lox_p(eqn: JaxprEqn) -> logdict:
        n_logs = eqn.params["n_logs"]
        logs_eqn = jax.tree.unflatten(eqn.params["structure"], eqn.invars[:n_logs])
        if argnames:
            if tags is None or not any(tag in tags for tag in eqn.params["tags"]):
                logs_eqn = logs_eqn.filter(lambda k, _: k in argnames)
        elif tags:
            if not any(tag in tags for tag in eqn.params["tags"]):
                logs_eqn = logdict({})
        return logs_eqn

    def spool_scan_p(eqn: JaxprEqn) -> tuple[JaxprEqn, logdict, list[JaxprEqn]]:
        inner_closed = eqn.params["jaxpr"]
        new_inner_jaxpr, logs_jaxpr = spool_jaxpr(inner_closed.jaxpr, argnames, tags)

        if not logs_jaxpr:
            return eqn, logdict({}), []

        logs_jaxpr_avals = jax.tree_util.tree_map(lambda l: l.aval, logs_jaxpr)
        logs_scan_avals = jax.tree_util.tree_map(
            lambda aval: ShapedArray((eqn.params["length"],) + aval.shape, aval.dtype),
            logs_jaxpr_avals,
        )
        logs_scan = jax.tree.map(lambda aval: Var(aval=aval), logs_scan_avals)

        new_eqn = eqn.replace(
            outvars=[*eqn.outvars, *jax.tree.leaves(logs_scan)],
            params={**eqn.params, "jaxpr": ClosedJaxpr(new_inner_jaxpr, inner_closed.consts)},
        )

        def unstack(logs_scan):
            return jax.tree.map(
                lambda l: l.reshape((-1,) + l.shape[2:]),
                logs_scan,
            )

        unstack_eqn, logs_eqn = apply(unstack, ctx, logs_scan)
        return new_eqn, logs_eqn, [unstack_eqn]

    def value_length(value: Any) -> int:
        leaves = jax.tree_util.tree_leaves(value)
        if not leaves:
            return 0
        return leaves[0].aval.shape[0]

    def materialize_default(default_value: Any, template: Any) -> Any:
        def entry_shape(aval):
            return (1, *aval.shape[1:])

        template_structure = jax.tree_util.tree_structure(template)
        default_structure = jax.tree_util.tree_structure(default_value)
        if default_structure == template_structure:
            return jax.tree_util.tree_map(
                lambda d, t: jax.numpy.broadcast_to(
                    jax.numpy.asarray(d, dtype=t.aval.dtype), entry_shape(t.aval)
                ),
                default_value,
                template,
            )
        if default_structure.num_leaves == 1:
            scalar = jax.tree_util.tree_leaves(default_value)[0]
            return jax.tree_util.tree_map(
                lambda t: jax.numpy.broadcast_to(
                    jax.numpy.asarray(scalar, dtype=t.aval.dtype), entry_shape(t.aval)
                ),
                template,
            )
        raise ValueError(
            "Default value structure must match logged value structure or be a scalar."
        )

    def extract_defaults(
        jaxpr_local: Jaxpr, consts_local: tuple[Any, ...] = ()
    ) -> dict[str, list[Any | None]]:
        defaults: dict[str, list[Any | None]] = {}
        del consts_local

        def append_defaults(new_defaults: dict[str, list[Any | None]]):
            for key, values in new_defaults.items():
                defaults.setdefault(key, []).extend(values)

        for local_eqn in jaxpr_local.eqns:
            if local_eqn.primitive == lox_p:
                n_logs = local_eqn.params["n_logs"]
                logs_flat = local_eqn.invars[:n_logs]
                logs_local = jax.tree.unflatten(local_eqn.params["structure"], logs_flat)
                default_mask_local = dict(
                    zip(local_eqn.params["default_keys"], local_eqn.params["default_mask"])
                )
                default_values_local = dict(
                    zip(local_eqn.params["default_keys"], local_eqn.params["default_values"])
                )
                if argnames:
                    if tags is None or not any(
                        tag in tags for tag in local_eqn.params["tags"]
                    ):
                        logs_local = logs_local.filter(lambda k, _: k in argnames)
                    else:
                        logs_local = logdict({})
                elif tags:
                    if not any(tag in tags for tag in local_eqn.params["tags"]):
                        logs_local = logdict({})
                append_defaults(
                    {
                        key: [
                            default_values_local[key]
                            if default_mask_local.get(key, False)
                            else None
                        ]
                        for key in logs_local
                    }
                )
            elif local_eqn.primitive == jax.extend.core.primitives.scan_p:
                scan_defaults = extract_defaults(
                    local_eqn.params["jaxpr"].jaxpr, local_eqn.params["jaxpr"].consts
                )
                append_defaults(
                    {
                        key: values * local_eqn.params["length"]
                        for key, values in scan_defaults.items()
                    }
                )
            elif local_eqn.primitive == jax.extend.core.primitives.jit_p:
                append_defaults(
                    extract_defaults(
                        local_eqn.params["jaxpr"].jaxpr,
                        local_eqn.params["jaxpr"].consts,
                    )
                )
            elif local_eqn.primitive == jax.extend.core.primitives.call_p:
                append_defaults(extract_defaults(local_eqn.params["call_jaxpr"]))
            elif local_eqn.primitive == jax._src.ad_checkpoint.remat_p:
                append_defaults(extract_defaults(local_eqn.params["jaxpr"]))
            elif local_eqn.primitive == jax.extend.core.primitives.cond_p:
                branch_defaults = [
                    extract_defaults(branch.jaxpr, branch.consts)
                    for branch in local_eqn.params["branches"]
                ]
                cond_defaults: dict[str, list[Any | None]] = {}
                all_keys = set().union(*(branch.keys() for branch in branch_defaults))
                for key in all_keys:
                    target = max(len(branch.get(key, [])) for branch in branch_defaults)
                    values = []
                    for idx in range(target):
                        default_value = None
                        for branch in branch_defaults:
                            if idx < len(branch.get(key, [])) and branch[key][idx] is not None:
                                default_value = branch[key][idx]
                                break
                        values.append(default_value)
                    cond_defaults[key] = values
                append_defaults(cond_defaults)

        return defaults

    def spool_cond_p(eqn: JaxprEqn) -> tuple[JaxprEqn, logdict, list[JaxprEqn]]:
        branches = eqn.params["branches"]
        new_branches = []
        logs_branches = []
        defaults_branches = []
        for branch in branches:
            new_branch_jaxpr, logs_branch = spool_jaxpr(branch.jaxpr, argnames, tags)
            new_branches.append(ClosedJaxpr(new_branch_jaxpr, branch.consts))
            logs_branches.append(logs_branch)
            defaults_branches.append(extract_defaults(branch.jaxpr, branch.consts))

        if not any(logs_branches):
            return eqn, logdict({}), []

        all_keys = set().union(*(logs_branch.keys() for logs_branch in logs_branches))
        target_lengths = {
            key: max(
                value_length(logs_branch[key]) if key in logs_branch else 0
                for logs_branch in logs_branches
            )
            for key in all_keys
        }

        defaults_by_key: dict[str, list[Any | None]] = {}
        for key in all_keys:
            target = target_lengths[key]
            defaults_by_key[key] = []
            for idx in range(target):
                default_value = None
                for branch_defaults in defaults_branches:
                    values = branch_defaults.get(key, [])
                    if idx < len(values) and values[idx] is not None:
                        default_value = values[idx]
                        break
                defaults_by_key[key].append(default_value)

        padded_branches = []
        padded_logs_branches = []
        all_step_names = set().union(*(logs_branch.steps.keys() for logs_branch in logs_branches))
        for branch, logs_branch in zip(new_branches, logs_branches):
            pads_data = {}
            pads_steps = {}
            for key in all_keys:
                target = target_lengths[key]
                branch_count = value_length(logs_branch[key]) if key in logs_branch else 0
                if branch_count >= target:
                    continue
                missing_defaults = defaults_by_key[key][branch_count:target]
                if any(default_value is None for default_value in missing_defaults):
                    raise ValueError(
                        "Divergent logging branches detected in jax.lax.cond. "
                        f"Missing defaults for key '{key}'."
                    )
                template = next(
                    logs_other[key]
                    for logs_other in logs_branches
                    if key in logs_other and value_length(logs_other[key]) == target
                )
                pads_data[key] = jax.tree_util.tree_map(
                    lambda *vals: jax.numpy.concatenate(vals, axis=0),
                    *[
                        materialize_default(default_value, template)
                        for default_value in missing_defaults
                    ],
                )
                for step_name in all_step_names:
                    if step_name not in pads_steps:
                        pads_steps[step_name] = {}
                    dtype = (
                        logs_branch.steps[step_name][key].aval.dtype
                        if step_name in logs_branch.steps and key in logs_branch.steps[step_name]
                        else jax.numpy.int32
                    )
                    pads_steps[step_name][key] = jax.numpy.zeros(
                        (target - branch_count,), dtype=dtype
                    )

            if not pads_data and not pads_steps:
                padded_branches.append(branch)
                padded_logs_branches.append(logs_branch)
                continue

            def pad_logs(logs):
                data = {}
                for key in all_keys:
                    if key in logs:
                        if key in pads_data:
                            data[key] = jax.tree_util.tree_map(
                                lambda existing, pad: jax.numpy.concatenate(
                                    (existing, pad), axis=0
                                ),
                                logs[key],
                                pads_data[key],
                            )
                        else:
                            data[key] = logs[key]
                    else:
                        data[key] = pads_data[key]
                steps = {}
                for step_name in all_step_names:
                    step_data = {}
                    for key in all_keys:
                        if step_name in logs.steps and key in logs.steps[step_name]:
                            if key in pads_steps.get(step_name, {}):
                                step_data[key] = jax.numpy.concatenate(
                                    (
                                        logs.steps[step_name][key],
                                        pads_steps[step_name][key],
                                    ),
                                    axis=0,
                                )
                            else:
                                step_data[key] = logs.steps[step_name][key]
                        elif key in pads_steps.get(step_name, {}):
                            step_data[key] = pads_steps[step_name][key]
                    if step_data:
                        steps[step_name] = stepdict(step_data)
                return logdict(data, **steps)

            pad_eqn, padded_logs = apply(pad_logs, ctx, logs_branch)
            n_logs_outvars = len(jax.tree.leaves(logs_branch))
            base_outvars = (
                branch.jaxpr.outvars[:-n_logs_outvars]
                if n_logs_outvars
                else list(branch.jaxpr.outvars)
            )
            branch_jaxpr = branch.jaxpr.replace(
                eqns=[*branch.jaxpr.eqns, pad_eqn],
                outvars=[*base_outvars, *jax.tree.leaves(padded_logs)],
            )
            padded_branches.append(ClosedJaxpr(branch_jaxpr, branch.consts))
            padded_logs_branches.append(padded_logs)

        logs_eqn = jax.tree.map(
            lambda l: Var(aval=ShapedArray(l.aval.shape, l.aval.dtype)),
            padded_logs_branches[0],
        )
        new_eqn = eqn.replace(
            outvars=[*eqn.outvars, *jax.tree.leaves(logs_eqn)],
            params={**eqn.params, "branches": tuple(padded_branches)},
        )
        return new_eqn, logs_eqn, []

    def spool_while_p(eqn: JaxprEqn) -> tuple[JaxprEqn, logdict, list[JaxprEqn]]:
        _, logs_cond = spool_jaxpr(eqn.params["cond_jaxpr"].jaxpr, argnames, tags)
        _, logs_body = spool_jaxpr(eqn.params["body_jaxpr"].jaxpr, argnames, tags)
        if logs_cond or logs_body:
            print(
                "Warning: Spooling for while loops is not supported due to non-static length."
            )
        return eqn, logdict({}), []

    def spool_jit_p(eqn: JaxprEqn) -> tuple[JaxprEqn, logdict, list[JaxprEqn]]:
        inner_closed = eqn.params["jaxpr"]
        new_inner_jaxpr, logs_jaxpr = spool_jaxpr(inner_closed.jaxpr, argnames, tags)
        if logs_jaxpr:
            logs_eqn = jax.tree.map(
                lambda l: Var(aval=ShapedArray(l.aval.shape, l.aval.dtype)), logs_jaxpr
            )
            const_literals = [Literal(c, jax.typeof(c)) for c in inner_closed.consts]
            call_jaxpr = new_inner_jaxpr.replace(
                constvars=[],
                invars=[*new_inner_jaxpr.constvars, *new_inner_jaxpr.invars],
            )
            new_eqn = eqn.replace(
                primitive=jax.extend.core.primitives.call_p,
                invars=[*const_literals, *eqn.invars],
                outvars=[*eqn.outvars, *jax.tree.leaves(logs_eqn)],
                params={"call_jaxpr": call_jaxpr},
            )
            return new_eqn, logs_eqn, []
        else:
            return eqn, logdict({}), []

    def spool_call_p(eqn: JaxprEqn) -> tuple[JaxprEqn, logdict, list[JaxprEqn]]:
        new_call_jaxpr, logs_call_jaxpr = spool_jaxpr(eqn.params["call_jaxpr"], argnames, tags)
        if not logs_call_jaxpr:
            return eqn, logdict({}), []

        logs_eqn = jax.tree.map(
            lambda l: Var(aval=ShapedArray(l.aval.shape, l.aval.dtype)), logs_call_jaxpr
        )
        new_eqn = eqn.replace(
            outvars=[*eqn.outvars, *jax.tree_util.tree_leaves(logs_eqn)],
            params={**eqn.params, "call_jaxpr": new_call_jaxpr},
        )
        return new_eqn, logs_eqn, []

    def spool_remat_p(eqn: JaxprEqn) -> tuple[JaxprEqn, logdict, list[JaxprEqn]]:
        new_remat_jaxpr, logs_remat_jaxpr = spool_jaxpr(eqn.params["jaxpr"], argnames, tags)
        if not logs_remat_jaxpr:
            return eqn, logdict({}), []

        logs_eqn = jax.tree.map(
            lambda l: Var(aval=ShapedArray(l.aval.shape, l.aval.dtype)),
            logs_remat_jaxpr,
        )
        new_eqn = eqn.replace(
            outvars=[*eqn.outvars, *jax.tree_util.tree_leaves(logs_eqn)],
            params={**eqn.params, "jaxpr": new_remat_jaxpr},
        )
        return new_eqn, logs_eqn, []

    new_eqns = []
    extra_eqns = []
    logs_eqns = []

    for eqn in jaxpr.eqns:
        new_eqn = eqn
        logs_eqn = None
        extra = []

        if eqn.primitive == lox_p:
            logs_eqn = spool_lox_p(eqn)
        elif eqn.primitive == jax.extend.core.primitives.scan_p:
            new_eqn, logs_eqn, extra = spool_scan_p(eqn)
        elif eqn.primitive == jax.extend.core.primitives.cond_p:
            new_eqn, logs_eqn, extra = spool_cond_p(eqn)
        elif eqn.primitive == jax.extend.core.primitives.while_p:
            new_eqn, logs_eqn, extra = spool_while_p(eqn)
        elif eqn.primitive == jax.extend.core.primitives.jit_p:
            new_eqn, logs_eqn, extra = spool_jit_p(eqn)
        elif eqn.primitive == jax.extend.core.primitives.call_p:
            new_eqn, logs_eqn, extra = spool_call_p(eqn)
        elif eqn.primitive == jax._src.ad_checkpoint.remat_p:
            new_eqn, logs_eqn, extra = spool_remat_p(eqn)

        new_eqns.append(new_eqn)
        extra_eqns.extend(extra)
        if logs_eqn:
            logs_eqns.append(logs_eqn)

    new_outvars = list(jaxpr.outvars)
    if logs_eqns:

        def combine(logs_eqns):
            """Combines the logs from multiple equations into a single logdict."""
            logs_jaxpr = logs_eqns[0]
            for logs_eqn in logs_eqns[1:]:
                logs_jaxpr += logs_eqn
            return logs_jaxpr

        combine_eqn, logs_jaxpr = apply(combine, ctx, logs_eqns)
        extra_eqns.append(combine_eqn)
        new_outvars.extend(jax.tree_util.tree_leaves(logs_jaxpr))
    else:
        logs_jaxpr = logdict({})

    new_jaxpr = jaxpr.replace(outvars=new_outvars, eqns=new_eqns + extra_eqns)
    return new_jaxpr, logs_jaxpr
